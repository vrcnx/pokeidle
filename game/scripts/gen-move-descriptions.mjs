#!/usr/bin/env node
/**
 * Emit src/data/moveDescriptions.ts from @pkmn/dex.
 *
 * Source: @pkmn/dex (MIT), which is Pokémon Showdown's dataset and is ALREADY
 * a dependency of this client — nothing is fetched and nothing new is added.
 * Its `shortDesc` is Showdown's own one-line summary of what a move does, so
 * it is a description of MECHANICS rather than the games' flavour text.
 *
 * ── WHY GENERATED AND COMMITTED, NOT READ AT RUNTIME ─────────────────────
 * @pkmn/dex is ~2MB of move data. Pulling it into the client bundle to render
 * one sentence per move card would cost every player that download forever,
 * on a page that needs four strings at a time. The generated file is the 1,038
 * sentences and nothing else.
 *
 * Committing it also means a `npm i` that bumps @pkmn/dex cannot silently
 * change what the game tells players. The diff shows up in review.
 *
 * ── WHICH GENERATION, AND WHY IT IS PINNED ───────────────────────────────
 * GEN 9, because that is what this game's move table already is: measured
 * across all nine generations, 1,031 of 1,038 powers and 1,038 of 1,038
 * accuracies match Gen 9, and every earlier generation matches worse. The
 * house rule is to work off the latest generation always.
 *
 * The pin matters because a description is a PROMISE about behaviour. Two
 * rows in this table had drifted — Fire Blast carried Gen 9's power beside
 * Gen 1's 30% burn chance, and High Jump Kick was still at the Gen 4 power —
 * and importing text without checking would have shipped 1,038 sentences of
 * which two were lies. moveGeneration.test.ts now holds the whole table to
 * Gen 9 so that cannot recur silently.
 *
 * Usage:  npx vite-node scripts/gen-move-descriptions.mjs
 */

import { writeFileSync } from "node:fs";
import { Dex } from "@pkmn/dex";
import { moves } from "../src/data/moves.ts";

/** The generation this game is. See the header. */
const GEN = 9;

/** Showdown's key for a move: its display name, lowercased, alphanumerics
 *  only. "High Jump Kick" → "highjumpkick". */
const keyOf = (name) => name.toLowerCase().replace(/[^a-z0-9]/g, "");

const dex = Dex.forGen(GEN);
const out = [];
const missing = [];

for (const [id, move] of Object.entries(moves)) {
  const theirs = dex.moves.get(keyOf(move.name));
  if (!theirs?.exists || !theirs.shortDesc) {
    missing.push(move.name);
    continue;
  }
  // shortDesc, not desc. `desc` is the full rules text and runs to several
  // lines on anything complicated — it is reference material, and the card has
  // room for a sentence.
  out.push([id, theirs.shortDesc]);
}

out.sort((a, b) => a[0].localeCompare(b[0]));

// Keys are QUOTED unconditionally. Move ids are mostly camelCase and would be
// fine bare, but not all of them: `10000000voltthunderbolt` starts with a
// digit, which is not a valid identifier, and the generated file failed to
// parse at all. Quoting every key costs two characters and removes the class.
const body = out.map(([id, d]) => `  ${JSON.stringify(id)}: ${JSON.stringify(d)},`).join("\n");

writeFileSync(
  new URL("../src/data/moveDescriptions.ts", import.meta.url),
  `// GENERATED by scripts/gen-move-descriptions.mjs — do not edit by hand.
//
// One line per move, from @pkmn/dex (MIT) at generation ${GEN}. Regenerate with:
//     npx vite-node scripts/gen-move-descriptions.mjs
//
// These sentences are PROMISES about what a move does, so the numbers in them
// have to match src/data/moves.ts. tests/moveGeneration.test.ts holds the move
// table to generation ${GEN}, which is what keeps that true.

export const moveDescriptions: Record<string, string> = {
${body}
};
`,
  "utf8",
);

console.log(`wrote ${out.length} descriptions (gen ${GEN})`);
if (missing.length) {
  console.log(`no shortDesc for ${missing.length}: ${missing.join(", ")}`);
}
